"""Prove a stock Bazel genrule goes through the direct worker."""

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

from datadog_build_stress import logged_spawns


def run(args, private):
    ws = private / "ws"
    ws.mkdir()
    (ws / "MODULE.bazel").write_text('module(name="smoke")\n')
    (ws / "in.txt").write_bytes(b"from worker\n")
    (ws / "BUILD.bazel").write_text(
        'genrule(name="proof", srcs=["in.txt"], outs=["out.txt"], '
        'cmd="cat $(location in.txt) > $@", cmd_bat="type $(location in.txt) > $@")\n')
    ready, events = private/"ready", private/"events"
    worker = subprocess.Popen([sys.executable, "-B", str(Path(__file__).with_name("reapi_worker.py")),
                               "--root", str(private/"remote"), "--jobs", "2", "--mode", "shared",
                               "--ready-file", str(ready), "--events", str(events)], stdin=subprocess.PIPE)
    try:
        deadline = time.monotonic()+30
        while not ready.exists():
            if worker.poll() is not None or time.monotonic() > deadline:
                raise RuntimeError("Worker failed to start")
            time.sleep(.05)
        endpoint = json.loads(ready.read_text())["endpoint"]
        env = dict(os.environ, USE_BAZEL_VERSION="9.1.0")
        if os.name == "nt":
            env["BAZEL_SH"] = "C:/Program Files/Git/bin/bash.exe"
        command = [args.bazel, "--batch", "--ignore_all_rc_files", f"--output_user_root={private/'i'}",
                   f"--output_base={private/'o'}", "build", "//:proof",
                   "--incompatible_autoload_externally=", f"--remote_executor={endpoint}",
                   f"--remote_cache={endpoint}", "--remote_instance_name=local",
                   "--remote_download_outputs=all", "--spawn_strategy=remote",
                   "--noremote_local_fallback", "--noremote_upload_local_results", "--remote_retries=0",
                   f"--execution_log_json_file={private/'spawns'}"]
        if args.repository_cache:
            command += [f"--repository_cache={args.repository_cache.resolve()}"]
        result = subprocess.run(command, cwd=ws, env=env, capture_output=True, timeout=120)
        if result.returncode:
            raise RuntimeError(result.stderr.decode(errors="replace")[-6000:])
        spawns = logged_spawns(private/"spawns")
        expected, = (private/"o/execroot/_main/bazel-out").glob("*/bin/out.txt")
        if expected.read_bytes() != b"from worker\n":
            raise ValueError("Unexpected generated bytes")
        rows = [json.loads(line) for line in events.read_text().splitlines()]
        if not any(s["runner"] == "remote" for s in spawns) or sum(r["event"] == "start" for r in rows) != 1:
            raise AssertionError((spawns, rows))
        return {"spawns": spawns, "events": rows, "output": expected.read_text()}
    finally:
        if worker.poll() is None:
            worker.stdin.write(b"stop\n")
            worker.stdin.close()
            worker.wait(timeout=30)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--bazel", default="bazel")
    p.add_argument("--repository-cache", type=Path)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    with tempfile.TemporaryDirectory(prefix="rex-") as temp:
        report = run(args, Path(temp))
    args.output.write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
