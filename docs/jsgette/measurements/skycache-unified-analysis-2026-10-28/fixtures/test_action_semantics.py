import copy
from pathlib import Path
import tempfile
import unittest

import run_action_semantics as runner


def finished(code=0, failure=None):
    value = {'exitCode': {'name': 'SUCCESS'} if code == 0 else {'code': code}}
    if failure is not None:
        value['failureDetail'] = {'analysis': {'code': failure}}
    return {'id': {'buildFinished': {}}, 'finished': value, 'lastMessage': True}


def diagnostic(case):
    signature = ('is generated by these conflicting actions:' if case['failure_code'] == 'ACTION_CONFLICT'
                 else 'prefix of the other. These actions cannot be simultaneously present')
    return ' '.join([signature] + [runner.target(name) for name in case['names']]
                    + ['semantics/' + path for path in case['paths']])


class ActionSemanticsTest(unittest.TestCase):
    def test_terminal_accepts_proto_default_success_and_matching_failure(self):
        self.assertEqual(runner.terminal([finished()], 0)['exitCode']['name'], 'SUCCESS')
        self.assertEqual(runner.terminal([finished(1, 'ACTION_CONFLICT')], 1)
                         ['failureDetail']['analysis']['code'], 'ACTION_CONFLICT')

    def test_terminal_rejects_truncation_unposted_children_and_status_mismatch(self):
        missing_child = finished()
        missing_child['children'] = [{'targetCompleted': {'label': '//:missing'}}]
        duplicate_finish = [dict(finished(), lastMessage=False), finished()]
        for events, code in [([], 0), ([dict(finished(), lastMessage=False)], 0),
                             ([missing_child], 0), (duplicate_finish, 0), ([finished()], 1)]:
            with self.subTest(events=events, code=code), self.assertRaises(ValueError):
                runner.terminal(events, code)

    def test_expected_negative_cases_require_exact_structured_and_text_evidence(self):
        for case in runner.CASES[1:]:
            events = [finished(1, case['failure_code'])]
            self.assertTrue(runner.validate_negative(events, 1, diagnostic(case), case)['passed'])
            for bad_events, code, text in [
                    (events, 0, diagnostic(case)),
                    ([finished(1, 'CONFIGURED_VALUE_CREATION_FAILED')], 1, diagnostic(case)),
                    (events, 1, 'unrelated failure'),
                    (events, 1, diagnostic(case).replace(runner.target(case['names'][1]), '//:other')),
                    (events, 1, diagnostic(case).replace('semantics/', 'elsewhere/'))]:
                with self.subTest(case=case['name'], code=code, text=text), self.assertRaises(ValueError):
                    runner.validate_negative(bad_events, code, text, case)

    def test_normalized_0555_mode_is_recorded_for_both_action_flags(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            files = []
            for name in ['plain.txt', 'executable.txt']:
                path = root / name
                path.write_bytes(b'fixture')
                path.chmod(0o555)
                files.append({'name': name, 'uri': path.as_uri()})
            observations = runner.observe_modes([{'namedSetOfFiles': {'files': files}}], root,
                                                {'plain.txt': False, 'executable.txt': True})
            self.assertEqual(observations['plain.txt']['mode_octal'], '0o555')
            self.assertTrue(observations['plain.txt']['owner_executable'])
            self.assertFalse(observations['plain.txt']['declared_action_make_executable'])
            self.assertTrue(observations['executable.txt']['declared_action_make_executable'])

    def test_mode_observation_requires_all_outputs_inside_owned_directory(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            owned = root / 'owned'
            owned.mkdir()
            path = root / 'outside.txt'
            path.write_bytes(b'outside')
            for events in [[], [{'namedSetOfFiles': {'files': [{'name': 'out', 'uri': path.as_uri()}]}}]]:
                with self.subTest(events=events), self.assertRaises(ValueError):
                    runner.observe_modes(events, owned, {'out': False})

    def test_shared_success_requires_one_file_write_not_just_equal_output_bytes(self):
        events = [{'buildMetrics': {'actionSummary': {'actionData': [
            {'mnemonic': 'FileWrite', 'actionsCreated': '2', 'actionsExecuted': '1'},
            {'mnemonic': 'BazelWorkspaceStatusAction', 'actionsExecuted': '1'}]}}}]
        self.assertEqual(runner.validate_file_write_executions(events, 1), 1)
        duplicate = copy.deepcopy(events)
        duplicate[0]['buildMetrics']['actionSummary']['actionData'][0]['actionsExecuted'] = '2'
        with self.assertRaises(ValueError):
            runner.validate_file_write_executions(duplicate, 1)
        with self.assertRaises(ValueError):
            runner.validate_file_write_executions([{'buildMetrics': {}}], 1)

    def test_producer_success_requires_four_file_write_executions(self):
        events = [{'buildMetrics': {'actionSummary': {'actionData': [
            {'mnemonic': 'FileWrite', 'actionsExecuted': '4'}]}}}]
        self.assertEqual(runner.validate_file_write_executions(events, 4), 4)
        with self.assertRaises(ValueError):
            runner.validate_file_write_executions(events, 1)

    def test_hit_count_selects_configured_targets_and_requires_metrics(self):
        events = [{'buildMetrics': {'remoteAnalysisCacheStatistics': {'cacheHitsBySkyfunction': [
            {'key': 'CONFIGURED_TARGET', 'value': '2'}, {'key': 'OTHER', 'value': '99'}]}}}]
        self.assertEqual(runner.configured_target_hits(events), 2)
        self.assertEqual(runner.configured_target_hits([{'buildMetrics': {}}]), 0)
        for invalid in [[], events * 2]:
            with self.assertRaises(ValueError):
                runner.configured_target_hits(invalid)

    def test_shared_and_separate_producer_oracles(self):
        shared, modes = runner.success_spec([(runner.CASES[0], 0), (runner.CASES[0], 1)])
        self.assertEqual(len(shared['targets']), 2)
        self.assertEqual(len(shared['outputs']), 1)
        self.assertEqual(modes, {'semantics/shared.txt': False})
        for side in [0, 1]:
            spec, modes = runner.success_spec([(case, side) for case in runner.CASES])
            self.assertEqual(len(spec['targets']), 4)
            self.assertEqual(len(spec['outputs']), 4)
            self.assertEqual(modes['semantics/mode.txt'], side == 1)
        for case in runner.CASES[1:3]:
            with self.assertRaises(ValueError):
                runner.success_spec([(case, 0), (case, 1)])


if __name__ == '__main__':
    unittest.main()
