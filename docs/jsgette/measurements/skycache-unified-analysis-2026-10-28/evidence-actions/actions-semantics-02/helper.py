#!/usr/bin/env python3
"""Correctness-only native matrix for the generated action_fanout semantics."""

import argparse
import importlib.util
import json
import os
from pathlib import Path
import shutil
import stat
import sys
from urllib.parse import urlsplit
from urllib.request import url2pathname

HARNESS = Path(__file__).resolve().parent.parent / 'paired_baseline.py'
module_spec = importlib.util.spec_from_file_location('paired_baseline', HARNESS)
baseline = importlib.util.module_from_spec(module_spec)
module_spec.loader.exec_module(baseline)

CASES = [
    {'name': 'shared', 'names': ['shared_left', 'shared_right'],
     'paths': ['shared.txt', 'shared.txt'], 'tags': ['same', 'same'],
     'executable': [False, False], 'failure_code': None},
    {'name': 'content', 'names': ['content_left', 'content_right'],
     'paths': ['content.txt', 'content.txt'], 'tags': ['left', 'right'],
     'executable': [False, False], 'failure_code': 'ACTION_CONFLICT'},
    {'name': 'mode', 'names': ['mode_left', 'mode_right'],
     'paths': ['mode.txt', 'mode.txt'], 'tags': ['same', 'same'],
     'executable': [False, True], 'failure_code': 'ACTION_CONFLICT'},
    {'name': 'prefix', 'names': ['prefix_file', 'prefix_child'],
     'paths': ['tree', 'tree/leaf.txt'], 'tags': ['same', 'same'],
     'executable': [False, False], 'failure_code': 'ARTIFACT_PREFIX_CONFLICT'},
]


def target(name):
    return '//semantics:' + name


def success_spec(selections):
    import hashlib
    targets, outputs, modes = [], {}, {}
    for case, index in selections:
        targets.append(target(case['names'][index]))
        path = case['paths'][index]
        text = f"skycache_action_fanout_v1\noutput={path}\ntag={case['tags'][index]}\n"
        name = 'semantics/' + path
        digest = hashlib.sha256(text.encode()).hexdigest()
        if name in outputs and (outputs[name] != digest or modes[name] != case['executable'][index]):
            raise ValueError('a successful specification cannot have conflicting outputs')
        outputs[name] = digest
        modes[name] = case['executable'][index]
    return {'schema_version': 1, 'targets': targets, 'outputs': outputs}, modes


def terminal(events, process_exit_code):
    if [i for i, event in enumerate(events) if event.get('lastMessage') is True] != [len(events) - 1]:
        raise ValueError('BEP requires exactly one lastMessage on its final event')
    finished = [event for event in events if 'buildFinished' in event.get('id', {})]
    if len(finished) != 1 or 'aborted' in finished[0]:
        raise ValueError('BEP requires one non-aborted buildFinished')
    value = finished[0].get('finished', {})
    code = value.get('exitCode')
    if not isinstance(code, dict) or code.get('code', 0) != process_exit_code:
        raise ValueError('BEP exit status disagrees with process exit')
    identity = lambda item: json.dumps(item, sort_keys=True, separators=(',', ':'))
    posted = {identity(event.get('id', {})) for event in events}
    announced = {identity(child) for event in events for child in event.get('children', [])}
    if announced - posted:
        raise ValueError('BEP is missing announced child events')
    return value


def build_metrics(events):
    metrics = [event['buildMetrics'] for event in events if 'buildMetrics' in event]
    if len(metrics) != 1:
        raise ValueError('BEP must contain exactly one buildMetrics event')
    return metrics[0]


def configured_target_hits(events):
    stats = build_metrics(events).get('remoteAnalysisCacheStatistics', {})
    return sum(int(item.get('value', 0)) for item in stats.get('cacheHitsBySkyfunction', [])
               if item.get('key') == 'CONFIGURED_TARGET')


def file_write_executions(events):
    entries = build_metrics(events).get('actionSummary', {}).get('actionData', [])
    return sum(int(item.get('actionsExecuted', 0)) for item in entries
               if item.get('mnemonic') == 'FileWrite')


def validate_file_write_executions(events, expected):
    actual = file_write_executions(events)
    if actual != expected:
        raise ValueError(f'expected {expected} executed FileWrite actions, found {actual}')
    return actual


def validate_negative(events, process_exit_code, stderr, case):
    finished = terminal(events, process_exit_code)
    if process_exit_code != 1:
        raise ValueError('expected ordinary build failure exit 1, not crash/timeout/success')
    detail = finished.get('failureDetail', {})
    actual = detail.get('analysis', {}).get('code')
    if actual != case['failure_code']:
        raise ValueError(f"expected {case['failure_code']}, found {actual!r}")
    if any(target(name) not in stderr for name in case['names']):
        raise ValueError('conflict diagnostic must name both requested owners')
    if any('semantics/' + path not in stderr for path in case['paths']):
        raise ValueError('conflict diagnostic must identify the intended output paths')
    signature = ('is generated by these conflicting actions:' if actual == 'ACTION_CONFLICT'
                 else 'prefix of the other. These actions cannot be simultaneously present')
    if signature not in stderr:
        raise ValueError('expected exact action-conflict diagnostic signature')
    return {'passed': True, 'expected_failure': actual, 'failure_detail': detail,
            'terminal_complete': True, 'owner_and_path_diagnostic_matched': True}


def observe_modes(events, output_base, modes):
    """Record physical output modes, which Bazel normalizes after action execution."""
    observed = {}
    for event in events:
        for item in event.get('namedSetOfFiles', {}).get('files', []):
            name = item.get('name')
            if name not in modes:
                continue
            uri = urlsplit(item.get('uri', ''))
            if uri.scheme != 'file' or uri.netloc not in ('', 'localhost'):
                raise ValueError('mode oracle requires local output files')
            path = baseline.inside(Path(url2pathname(uri.path)), output_base)
            mode = stat.S_IMODE(path.stat().st_mode)
            executable = bool(mode & stat.S_IXUSR)
            observed[name] = {'mode_octal': oct(mode), 'owner_executable': executable,
                              'declared_action_make_executable': modes[name]}
    if set(observed) != set(modes):
        raise ValueError('mode observations did not find every successful output')
    return observed


def run(args):
    if not sys.platform.startswith('linux'):
        raise ValueError('run native commands on Linux/WSL')
    binary = args.bazel.resolve(strict=True)
    original = args.workspace.resolve(strict=True)
    # This helper deliberately targets only the separate generated tiny semantic package.
    declarations = json.loads((original / 'semantic-cases.json').read_text())
    declared = set(declarations['success_case']['targets'])
    declared.update(t for case in declarations['failure_cases'] for t in case['targets'])
    if declared != {target(name) for case in CASES for name in case['names']}:
        raise ValueError('workspace semantic cases do not match this runner')
    input_hashes = baseline.inventory(original)
    root = args.run_dir.absolute()
    if root.exists() or root.is_symlink() or root.resolve().is_relative_to(original):
        raise ValueError('run directory must be new and outside the input workspace')
    root.mkdir()
    root = root.resolve()
    workspace = root / 'workspace'
    shutil.copytree(original, workspace)
    for name in ['home', 'tmp', 'links', 'runs', 'caches']:
        (root / name).mkdir()
    environment = {'PATH': os.environ.get('PATH', '/usr/bin:/bin'), 'HOME': str(root / 'home'),
                   'TMPDIR': str(root / 'tmp'), 'LANG': 'C.UTF-8', 'LC_ALL': 'C.UTF-8', 'TZ': 'UTC'}
    if 'JAVA_HOME' in os.environ:
        environment['JAVA_HOME'] = os.environ['JAVA_HOME']
    manifest = {
        'schema_version': 1, 'purpose': 'correctness matrix; not a performance experiment',
        'binary': {'path': str(binary), 'sha256': baseline.digest(binary)},
        'binary_source_binding': 'not verified; operator supplies binary provenance separately',
        'helper': {'path': str(Path(__file__).resolve()), 'sha256': baseline.digest(__file__)},
        'harness': {'path': str(HARNESS), 'sha256': baseline.digest(HARNESS)},
        'fixture_sha256': input_hashes, 'environment': environment,
        'host': baseline.host_description(), 'heap_mb': 2048, 'settings': baseline.SETTINGS,
        'cases': CASES,
        'restoration_evidence': 'Exact aggregate CONFIGURED_TARGET hits 0/1/2, combined with deliberately disjoint producer target selections. This is not per-label hit instrumentation.',
        'execution_evidence': 'Shared success requires exactly one executed FileWrite action; each producer requires four. Fresh output bases and disabled ordinary action caches isolate these executions.',
        'output_mode_contract': 'Physical modes are diagnostic only: Bazel normalizes regular outputs to 0555 by default (0755 with experimental_writable_outputs). The action makeExecutable flag remains part of the FileWrite action key and is checked by the mode-conflict case.',
        'plan': 'four cold cases; left-owner seed; four restored-left/local-right cases; right-owner seed added to a copy of left seed; four restored/restored cases',
    }
    baseline.save(root / 'manifest.json', manifest)
    shutil.copyfile(__file__, root / 'helper.py')
    shutil.copyfile(HARNESS, root / 'paired_baseline.py')
    summary = {'schema_version': 1, 'status': 'running', 'runs': []}

    def check_identity():
        if baseline.digest(binary) != manifest['binary']['sha256']:
            raise ValueError('binary changed during the matrix')
        if baseline.digest(HARNESS) != manifest['harness']['sha256']:
            raise ValueError('paired harness changed during the matrix')
        if baseline.digest(__file__) != manifest['helper']['sha256']:
            raise ValueError('semantic helper changed during the matrix')
        if baseline.inventory(workspace) != input_hashes:
            raise ValueError('fixture inputs changed during the matrix')

    def execute(label, selections, cache, expected_hits=None, failure_case=None):
        check_identity()
        directory = root / 'runs' / label
        targets = [target(case['names'][index]) for case, index in selections]
        argv = baseline.command(binary, root, directory, cache, targets, 2048)
        metrics = baseline.run_command(directory, argv, workspace, environment, 120,
                                       manifest['harness']['sha256'])
        row = {'label': label, 'targets': targets, 'cache': str(cache) if cache else None,
               'expected_configured_target_hits': expected_hits,
               'expected_failure': failure_case['failure_code'] if failure_case else None,
               'metrics': metrics, 'diagnostics_sha256': baseline.copy_diagnostics(directory)}
        summary['runs'].append(row)
        try:
            check_identity()
            if metrics['timed_out']:
                raise ValueError('command timed out')
            events = [json.loads(line) for line in (directory / 'build.bep.json').read_text().splitlines() if line]
            row['configured_target_hits'] = configured_target_hits(events)
            row['file_write_executions'] = file_write_executions(events)
            if failure_case:
                row['validation'] = validate_negative(events, metrics['exit_code'],
                                                       (directory / 'stderr.log').read_text(), failure_case)
            else:
                if metrics['exit_code'] != 0:
                    raise ValueError('expected successful command')
                spec, modes = success_spec(selections)
                row['validation'] = baseline.validate_outputs(directory / 'build.bep.json',
                                                               directory / 'output-base', spec)
                row['output_modes'] = observe_modes(events, directory / 'output-base', modes)
                # Every successful case here has one FileWrite action per distinct output path.
                # For shared owners this requires one execution, not merely equal final bytes.
                row['expected_file_write_executions'] = len(spec['outputs'])
                validate_file_write_executions(events, len(spec['outputs']))
            if expected_hits is not None and row['configured_target_hits'] != expected_hits:
                raise ValueError(f"expected {expected_hits} configured-target hits, found {row['configured_target_hits']}")
            row['status'] = 'passed'
        except Exception as error:
            row['status'] = 'failed'
            row['error'] = str(error)
        finally:
            row['raw_artifacts_sha256'] = {path.name: baseline.digest(path) for path in directory.iterdir() if path.is_file()}
            baseline.save(root / 'summary.json', summary)
        return row['status'] == 'passed'

    def cohort(name, seed, expected_hits):
        for case in CASES:
            cache = None
            if seed is not None:
                cache = root / 'caches' / (name + '-' + case['name'])
                shutil.copytree(seed, cache, symlinks=False)
            execute(name + '-' + case['name'], [(case, 0), (case, 1)], cache, expected_hits,
                    case if case['failure_code'] else None)

    try:
        cohort('cold', None, 0)
        left_seed = root / 'caches' / 'left-seed'
        if not execute('producer-left', [(case, 0) for case in CASES], left_seed):
            raise ValueError('left producer failed; dependent restored cases cannot run')
        if not list(left_seed.rglob('*.manifest')):
            raise ValueError('left producer did not publish a cache seed')
        cohort('restored-local', left_seed, 1)
        both_seed = root / 'caches' / 'both-seed'
        shutil.copytree(left_seed, both_seed, symlinks=False)
        if not execute('producer-right', [(case, 1) for case in CASES], both_seed):
            raise ValueError('right producer failed; dependent double-restored cases cannot run')
        cohort('restored-restored', both_seed, 2)
        summary['status'] = 'passed' if all(row['status'] == 'passed' for row in summary['runs']) else 'failed'
    except Exception as error:
        summary['status'] = 'failed'
        summary['error'] = str(error)
    finally:
        baseline.save(root / 'summary.json', summary)
    print(root)
    return 0 if summary['status'] == 'passed' else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bazel', type=Path, required=True)
    parser.add_argument('--workspace', type=Path, required=True)
    parser.add_argument('--run-dir', type=Path, required=True)
    return run(parser.parse_args())


if __name__ == '__main__':
    sys.exit(main())
